#include "libft.h"

char	*ft_strdup(const char *s1)
{
	char	*start;
	int		i;
	size_t	len;

	if (!s1)
		return (NULL);
	len = ft_strlen(s1);
	start = malloc(len + 1);
	if (!start)
		return (0);
	i = 0;
	while (s1[i] != '\0')
	{
		start[i] = s1[i];
		i++;
	}
	start[i] = 0;
	return (start);
}
