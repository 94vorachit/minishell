#include "libft.h"

int	ft_strrcmp(const char *s1, const char *s2, size_t n)
{
	size_t			i;

	i = n;
	while (*(unsigned char *)s1)
		s1++;
	while (i && (*(unsigned char *)s1 == ((unsigned char *)s2)[i]))
	{
		s1--;
		i--;
	}
	return (((unsigned char *)s1)[i] - ((unsigned char *)s2)[i]);
}
