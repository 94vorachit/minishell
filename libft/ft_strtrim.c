#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	size_t	start;
	size_t	size;

	if (!s1)
		return (0);
	start = 0;
	size = ft_strlen(s1) - 1;
	while (ft_strchr(set, s1[start]) && s1[start])
		start++;
	while (ft_strchr(set, s1[size]) && size > 0)
		size--;
	return (ft_substr(s1, start, size - start + 1));
}
